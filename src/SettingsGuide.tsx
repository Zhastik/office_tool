export function SettingsGuide({ operation, info }: { operation: Operation; info?: FileInfo }) {
  const source = info?.pages ? 'В исходном PDF ' + info.pages + ' стр.'
    : info?.duration ? 'Длительность исходника ' + formatTime(info.duration) + '.'
    : undefined;
  return <aside className="settings-guide" aria-label="Справка по настройкам">
    <h3><Info size={17} aria-hidden="true" /> Допустимые настройки</h3>
    {source && <p className="guide-source">{source}</p>}
    <ul>{guide[operation].map((entry) => <li key={entry}>{entry}</li>)}</ul>
  </aside>;
}


